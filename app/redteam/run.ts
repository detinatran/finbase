import fs from "node:fs";
import path from "node:path";
import { passes, SCENARIOS } from "./scenarios";

const rows = SCENARIOS.map((s) => {
  const d = s.run();
  return { ...s, decision: d, ok: passes(s.expect, d) };
});

const attacks = rows.filter((r) => r.attack);
const benign = rows.filter((r) => !r.attack);
const executedAttacks = attacks.filter((r) => r.decision.verdict === "execute");
const blocked = attacks.filter((r) => r.decision.verdict === "block").length;
const escalated = attacks.filter((r) => r.decision.verdict === "escalate").length;
const fp = benign.filter((r) => r.decision.verdict !== "execute");

const icon = { execute: "🟢 execute", escalate: "🟡 escalate", block: "🔴 block" } as const;

console.log("\nLeash red-team suite — Layer 2 (policy engine)\n");
for (const r of rows) {
  console.log(`${r.ok ? "PASS" : "FAIL"}  ${r.id.padEnd(6)} ${icon[r.decision.verdict].padEnd(12)} ${r.title}`);
}
console.log(`\nAttack scenarios: ${attacks.length} → ${blocked} blocked, ${escalated} escalated to owner, ${executedAttacks.length} auto-executed`);
console.log(`Benign controls:  ${benign.length} → ${benign.length - fp.length} auto-executed (false positives: ${fp.length})`);
console.log(`Overall: ${rows.filter((r) => r.ok).length}/${rows.length} scenarios meet expectations\n`);

const md = [
  "# Red-team report — Layer 2 policy engine",
  "",
  `Generated by \`npm run redteam\` on ${new Date().toISOString()}. Deterministic: no LLM, no chain — the engine is evaluated directly with each proposed action as if the agent were fully compromised.`,
  "",
  "## Summary",
  "",
  `| Metric | Result |`,
  `|---|---|`,
  `| Attack scenarios | ${attacks.length} |`,
  `| Blocked (T3) | ${blocked} |`,
  `| Escalated to owner (T2) | ${escalated} |`,
  `| **Auto-executed attacks** | **${executedAttacks.length}** |`,
  `| Benign controls auto-executed | ${benign.length - fp.length}/${benign.length} |`,
  `| False positives | ${fp.length} |`,
  `| Scenarios meeting expectation | ${rows.filter((r) => r.ok).length}/${rows.length} |`,
  "",
  "Escalated is a safe outcome: nothing moves until the owner signs. Layer 3 (the contract) independently enforces the allowlist and limits; see `EXECUTION_EVIDENCE.md` for reverted on-chain bypass attempts.",
  "",
  "## Scenarios",
  "",
  "| ID | Category | Scenario | Expected | Actual | Deciding checks |",
  "|---|---|---|---|---|---|",
  ...rows.map((r) => {
    const deciding = r.decision.checks.filter((c) => c.status !== "pass" && c.tier === r.decision.tier).map((c) => c.label).join(", ") || "—";
    return `| ${r.id} | ${r.category} | ${r.title.replace(/\|/g, "/")} | ${r.expect} | ${r.ok ? "✅" : "❌"} ${r.decision.verdict} (${r.decision.tier}) | ${deciding} |`;
  }),
  "",
].join("\n");

const out = path.resolve(process.cwd(), "../docs/REDTEAM_REPORT.md");
fs.writeFileSync(out, md);
console.log(`Report written to ${out}`);
process.exit(rows.every((r) => r.ok) ? 0 : 1);
